const BIN = fileURLToPath(new URL('../bin/lore.js', import.meta.url));
const tmp = () => fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'lore-mem-')));
const writeJsonl = (file, rows) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, rows.map((r) => JSON.stringify(r)).join('\n') + '\n');
};

// A small Claude Code session in `root`.
function claudeTranscript(root, file) {
  let n = 0;
  const usage = (ctx) => ({ input_tokens: 5, cache_read_input_tokens: ctx, cache_creation_input_tokens: 0, output_tokens: 10 });
  const a = (content, ctx = 50_000) => ({ type: 'assistant', sessionId: 'sess-claude-1', cwd: root, gitBranch: 'feat/x', timestamp: `2026-10-20T10:0${n}:00Z`, message: { id: `m${++n}`, usage: usage(ctx), content } });
  const u = (content, extra = {}) => ({ type: 'user', sessionId: 'sess-claude-1', cwd: root, timestamp: '2026-10-20T10:00:00Z', message: { content }, ...extra });
  writeJsonl(file, [
    { type: 'custom-title', customTitle: 'Add dark mode' },
    u('Add dark mode to the settings page'),
    u('<command-name>/model</command-name>'),
    u('Caveat: The messages below were generated by the user while running local commands.', { isMeta: true }),
    a([{ type: 'tool_use', id: 't1', name: 'Edit', input: { file_path: path.join(root, 'src/settings.tsx') } }]),
    u([{ type: 'tool_result', tool_use_id: 't1', content: 'ok' }]),
    a([{ type: 'tool_use', id: 't2', name: 'Bash', input: { command: 'npm test' } }], 120_000),
    u([{ type: 'tool_result', tool_use_id: 't2', content: 'Exit code 1\n1 failed', is_error: true }]),
    a([{ type: 'tool_use', id: 't3', name: 'TodoWrite', input: { todos: [{ content: 'Theme toggle', status: 'completed' }, { content: 'Persist choice', status: 'pending' }] } }]),
    u('no, dont use inline styles <system-reminder>ignore me</system-reminder>'),
    { type: 'attachment', timestamp: '2026-10-20T10:05:00Z', attachment: { type: 'queued_command', prompt: 'also keep the old theme as default', origin: { kind: 'human' } } },
    u('Summary of the conversation so far…', { isCompactSummary: true }),
    // A fake key, assembled at runtime so no secret-shaped string sits in the source.
    a([{ type: 'text', text: `Dark mode works; persisting the choice is next. KEY=${'sk_' + 'live_' + '0'.repeat(24)}` }], 200_000),
  ]);
}

test('Claude transcript → handoff with verbatim asks, files, checks, open items', async () => {
  const root = tmp();
  const file = path.join(root, 't.jsonl');
  claudeTranscript(root, file);
  const s = await readTranscript(file);
  assert.equal(s.agent, 'claude');
  assert.deepEqual(s.prompts.map((p) => p.text), ['Add dark mode to the settings page', 'no, dont use inline styles', 'also keep the old theme as default']);
  const { meta, markdown } = buildHandoff(s, { root, trigger: 'clear' });
  assert.equal(meta.title, 'Add dark mode');
  assert.equal(meta.files, 1);
  assert.equal(meta.open, 1);
  assert.match(markdown, /2\. ⚑ no, dont use inline styles/);
  assert.match(markdown, /- src\/settings\.tsx/);
  assert.match(markdown, /- ✗ `npm test`/);
  assert.match(markdown, /- \[ \] Persist choice/);
  assert.match(markdown, /branch `feat\/x`/);
  assert.match(markdown, /peak context 200K/);
  assert.match(markdown, /Summary \(written by the agent at compaction\)/);
  assert.ok(!markdown.includes('sk_live_'), 'secrets are redacted');
});

test('Codex rollout → handoff', async () => {
  const root = tmp();
  const file = path.join(root, '.codex/sessions/2026/10/20/rollout-x.jsonl');
  writeJsonl(file, [
    { type: 'session_meta', timestamp: '2026-10-20T09:00:00Z', payload: { id: 'codex-sess', cwd: root } },
    { type: 'event_msg', payload: { type: 'user_message', message: 'Fix the flaky login test' } },
    { type: 'response_item', payload: { type: 'function_call', name: 'exec_command', call_id: 'c1', arguments: JSON.stringify({ cmd: 'pytest -x tests/test_login.py' }) } },
    { type: 'response_item', payload: { type: 'function_call_output', call_id: 'c1', output: '1 passed' } },
    { type: 'response_item', payload: { type: 'custom_tool_call', name: 'apply_patch', call_id: 'c2', input: '*** Begin Patch\n*** Update File: tests/test_login.py\n@@\n*** End Patch' } },
    { type: 'response_item', payload: { type: 'function_call', name: 'update_plan', call_id: 'c3', arguments: JSON.stringify({ plan: [{ step: 'Add retry', status: 'completed' }, { step: 'Remove sleep', status: 'pending' }] }) } },
    { type: 'event_msg', payload: { type: 'token_count', info: { total_token_usage: { total_tokens: 9 }, last_token_usage: { input_tokens: 30_000 } } } },
    { type: 'event_msg', payload: { type: 'task_complete', last_agent_message: 'Login test fixed with a retry.' } },
  ]);
  const s = await readTranscript(file);
  assert.equal(s.agent, 'codex');
  const { markdown, meta } = buildHandoff(s, { root });
  assert.equal(meta.title, 'Fix the flaky login test');
  assert.match(markdown, /- tests\/test_login\.py/);
  assert.match(markdown, /- ✓ `pytest -x tests\/test_login\.py`/);
  assert.match(markdown, /- \[ \] Remove sleep/);
  assert.match(markdown, /Login test fixed with a retry\./);
});

// ---- the hook dispatcher, through the real binary ---------------------------------

function hookIn(home, payload) {
  const r = spawnSync(process.execPath, [BIN, 'hook'], {
    input: JSON.stringify(payload),
    encoding: 'utf8',
    env: { ...process.env, AGENTLORE_HOME: home, AGENTLORE_BIN: 'lore' },
  });
  assert.equal(r.status, 0, r.stderr);
  assert.ok(!fs.existsSync(path.join(home, 'errors.log')), fs.existsSync(path.join(home, 'errors.log')) && fs.readFileSync(path.join(home, 'errors.log'), 'utf8'));
  return r.stdout ? JSON.parse(r.stdout) : null;
}
const lore = (cwd, home, ...args) =>
  spawnSync(process.execPath, [BIN, ...args], { cwd, encoding: 'utf8', env: { ...process.env, AGENTLORE_HOME: home, AGENTLORE_BIN: 'lore' } });

test('hooks: brief at start, scoped lessons once, nudges, and a handoff at the end', () => {
  const root = tmp();
  const home = tmp();
  spawnSync('git', ['init', '-q'], { cwd: root });
  lore(root, home, 'learn', 'Always run pnpm lint before committing');
  lore(root, home, 'learn', 'Spacing comes from tokens', '--scope', 'src/ui/**');
  lore(root, home, 'learn', 'No Co-Authored-By trailers', '--scope', 'bash:git commit', '--user');
  const base = { session_id: 's1', cwd: root };

  const brief = hookIn(home, { ...base, hook_event_name: 'SessionStart', source: 'startup' }).hookSpecificOutput.additionalContext;
  assert.match(brief, /Always run pnpm lint before committing/);
  assert.match(brief, /2 more lessons apply to specific files or commands/);
  assert.doesNotMatch(brief, /Spacing comes from tokens/);
  assert.equal(hookIn(home, { ...base, hook_event_name: 'SessionStart', source: 'resume' }), null);

  const edit = { ...base, hook_event_name: 'PreToolUse', tool_name: 'Edit', tool_input: { file_path: path.join(root, 'src/ui/Card.tsx') } };
  assert.match(hookIn(home, edit).hookSpecificOutput.additionalContext, /lessons for src\/ui\/Card\.tsx:\n- Spacing comes from tokens/);
  assert.equal(hookIn(home, edit), null, 'shown once per session');
  hookIn(home, { ...base, hook_event_name: 'SessionStart', source: 'compact' });
  assert.ok(hookIn(home, edit), 'shown again after compaction forgot it');

  const commit = hookIn(home, { ...base, hook_event_name: 'PreToolUse', tool_name: 'Bash', tool_input: { command: 'git commit -m x' } });
  assert.match(commit.hookSpecificOutput.additionalContext, /No Co-Authored-By trailers/);
  assert.equal(commit.hookSpecificOutput.updatedInput, undefined);

  const codexTest = hookIn(home, { ...base, session_id: 'c1', transcript_path: '/h/.codex/sessions/rollout-1.jsonl', hook_event_name: 'PreToolUse', tool_name: 'Bash', tool_input: { command: 'npm test' } });
  assert.equal(codexTest, null, 'Codex: no rewrite (it would need "allow")');

  const corr = hookIn(home, { ...base, hook_event_name: 'UserPromptSubmit', prompt: 'no, dont use inline styles' });
  assert.match(corr.hookSpecificOutput.additionalContext, /lore learn/);
  assert.equal(hookIn(home, { ...base, hook_event_name: 'UserPromptSubmit', prompt: 'add a footer' }), null);

  const transcript = path.join(root, 'claude.jsonl');
  claudeTranscript(root, transcript);
  fs.appendFileSync(transcript, JSON.stringify({ type: 'assistant', message: { id: 'big', usage: { input_tokens: 0, cache_read_input_tokens: 450_000, cache_creation_input_tokens: 0 } } }) + '\n');
  const nudge = hookIn(home, { ...base, session_id: 's2', transcript_path: transcript, hook_event_name: 'UserPromptSubmit', prompt: 'next task' });
  assert.match(nudge.systemMessage, /450K tokens/);
  assert.equal(hookIn(home, { ...base, session_id: 's2', transcript_path: transcript, hook_event_name: 'UserPromptSubmit', prompt: 'next task' }), null, 'nudged once per 100K');

  hookIn(home, { ...base, transcript_path: transcript, hook_event_name: 'SessionEnd', reason: 'clear' });
  const saved = fs.readdirSync(path.join(root, '.lore/handoffs'));
  assert.equal(saved.length, 1);
  assert.match(saved[0], /add-dark-mode-sess-cla\.md$/);
  assert.match(fs.readFileSync(path.join(root, '.lore/.gitignore'), 'utf8'), /handoffs\//);

  const next = hookIn(home, { ...base, session_id: 's3', hook_event_name: 'SessionStart', source: 'clear' }).hookSpecificOutput.additionalContext;
  assert.match(next, /1\. Oct 20 · Add dark mode · claude · 1 files changed · 1 open/);
  const recalled = lore(root, home, 'recall', 'dark').stdout;
  assert.match(recalled, /^# Add dark mode/);
  assert.match(lore(root, home, 'recall').stdout, /1\. 2026-10-20 · Add dark mode/);
});

test('hook errors never reach the agent', () => {
  const home = tmp();
  const r = spawnSync(process.execPath, [BIN, 'hook'], { input: 'not json', encoding: 'utf8', env: { ...process.env, AGENTLORE_HOME: home } });
  assert.equal(r.status, 0);
  assert.equal(r.stdout, '');
  assert.match(fs.readFileSync(path.join(home, 'errors.log'), 'utf8'), /SyntaxError/);
});
